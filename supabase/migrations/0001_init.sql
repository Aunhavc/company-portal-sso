-- ---- profiles ---------------------------------------------------------------
drop policy if exists profiles_select_self  on public.profiles;
drop policy if exists profiles_select_admin on public.profiles;
drop policy if exists profiles_update_self  on public.profiles;
drop policy if exists profiles_admin_all    on public.profiles;

create policy profiles_select_self on public.profiles
  for select to authenticated
  using (id = public.auth0_sub());

create policy profiles_select_admin on public.profiles
  for select to authenticated
  using (public.is_admin());

-- แก้ได้เฉพาะแถวตัวเอง (role/is_active ถูกล็อกไว้ด้วย trigger ด้านล่าง)
create policy profiles_update_self on public.profiles
  for update to authenticated
  using (id = public.auth0_sub())
  with check (id = public.auth0_sub());

create policy profiles_admin_all on public.profiles
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- กันผู้ใช้ทั่วไปยกระดับตัวเองเป็น admin ผ่าน policy update_self
create or replace function public.guard_profile_privileges()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.is_admin() then
    return new;
  end if;

  -- ผู้ใช้ทั่วไปห้ามเปลี่ยนสิทธิ์ สถานะ หรือรหัสประจำตัวของตัวเอง
  new.role      := old.role;
  new.is_active := old.is_active;
  new.id        := old.id;

  -- อีเมลเปลี่ยนได้เฉพาะเมื่อค่าใหม่ตรงกับอีเมลใน JWT
  -- (เส้นทางเดียวที่ทำได้คือ RPC sync_profile ซึ่งอ่านค่าจากโทเคนเอง)
  -- ถ้าไม่มีเงื่อนไขนี้ อีเมลที่เปลี่ยนใน Auth0 จะไม่มีวันซิงค์ลงตารางนี้ได้เลย
  if new.email is distinct from old.email
     and lower(new.email) is distinct from lower(coalesce(auth.jwt() ->> 'email', '')) then
    new.email := old.email;
  end if;

  return new;
end;
$$;

drop trigger if exists profiles_guard on public.profiles;
create trigger profiles_guard
  before update on public.profiles
  for each row execute function public.guard_profile_privileges();

-- ---- apps -------------------------------------------------------------------
drop policy if exists apps_select_visible on public.apps;
drop policy if exists apps_admin_all      on public.apps;

create policy apps_select_visible on public.apps
  for select to authenticated
  using (
    is_active
    and public.auth0_sub() is not null
    and public.current_role_name() = any (allowed_roles)
  );

create policy apps_admin_all on public.apps
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- ---- announcements ----------------------------------------------------------
drop policy if exists announcements_select_published on public.announcements;
drop policy if exists announcements_admin_all        on public.announcements;

create policy announcements_select_published on public.announcements
  for select to authenticated
  using (published and public.auth0_sub() is not null);

create policy announcements_admin_all on public.announcements
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- =============================================================================
-- RPC: sync_profile()
-- Client ไม่ต้องส่ง id/email เอง — อ่านจาก JWT ทั้งหมด กัน spoofing
-- =============================================================================
create or replace function public.sync_profile(
  p_full_name  text default null,
  p_avatar_url text default null
)
returns public.profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sub    text := public.auth0_sub();
  v_email  text := coalesce(auth.jwt() ->> 'email', auth.jwt() -> 'user_metadata' ->> 'email');
  v_result public.profiles;
begin
  if v_sub is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  if v_email is null then
    raise exception 'JWT ไม่มี claim email — ตรวจสอบ Auth0 Post-Login Action' using errcode = '22023';
  end if;

  insert into public.profiles as p (id, email, full_name, avatar_url, last_login_at)
  values (v_sub, lower(v_email), p_full_name, p_avatar_url, now())
  on conflict (id) do update
    set email         = excluded.email,
        full_name     = coalesce(excluded.full_name, p.full_name),
        avatar_url    = coalesce(excluded.avatar_url, p.avatar_url),
        last_login_at = now()
  returning * into v_result;

  if not v_result.is_active then
    raise exception 'บัญชีนี้ถูกระงับการใช้งาน' using errcode = '28000';
  end if;

  return v_result;
end;
$$;

revoke all on function public.sync_profile(text, text) from public;
grant execute on function public.sync_profile(text, text) to authenticated;

