create extension if not exists "pgcrypto";

-- -----------------------------------------------------------------------------
-- Helper: ดึง Auth0 subject (user id) จาก JWT ที่แนบมากับ request
-- -----------------------------------------------------------------------------
create or replace function public.auth0_sub()
returns text
language sql
stable
as $$
  select nullif(auth.jwt() ->> 'sub', '');
$$;

comment on function public.auth0_sub() is 'Auth0 user id (sub) ของ request ปัจจุบัน — null ถ้าไม่ได้ล็อกอิน';

-- -----------------------------------------------------------------------------
-- 1) profiles — โปรไฟล์พนักงานที่ซิงค์มาจาก Auth0
-- -----------------------------------------------------------------------------
create table if not exists public.profiles (
  id            text primary key,                    -- Auth0 sub เช่น 'auth0|677a...'
  email         text not null unique,
  full_name     text,
  avatar_url    text,
  role          text not null default 'user'
                  check (role in ('user', 'admin')),
  department    text,
  is_active     boolean not null default true,
  last_login_at timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists profiles_email_idx on public.profiles (lower(email));
create index if not exists profiles_role_idx  on public.profiles (role) where role = 'admin';

-- -----------------------------------------------------------------------------
-- 2) apps — ทะเบียนแอปที่แสดงบนหน้า Portal  ★ เพิ่มแอปใหม่ได้จากหน้า Admin
-- -----------------------------------------------------------------------------
create table if not exists public.apps (
  id             bigint generated by default as identity primary key,
  slug           text not null unique,               -- ใช้อ้างอิงในโค้ด เช่น 'erp'
  name           text not null,
  description    text,
  category       text not null default 'ทั่วไป',

  -- ★ แกนหลัก: แอปนี้อยู่ฝั่งไหน
  network        text not null default 'internet'
                   check (network in ('internet', 'intranet')),

  url            text not null,                      -- ปลายทางเมื่อคลิก
  sso_url        text,                               -- ถ้ามี = ใช้ URL นี้แทน url เพื่อเข้าผ่าน SSO
  health_url     text,                               -- endpoint สำหรับ probe (เช่น .../ping.php)

  icon           text not null default '🗂️',         -- emoji หรือชื่อไอคอน
  accent         text not null default 'slate'
                   check (accent in ('slate','blue','emerald','amber','rose','violet','cyan','orange')),

  open_in_new_tab boolean not null default true,
  allowed_roles   text[] not null default array['user','admin'],
  sort_order      integer not null default 100,
  is_active       boolean not null default true,

  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index if not exists apps_active_idx on public.apps (is_active, sort_order);

comment on column public.apps.network    is 'internet = เข้าได้จากทุกที่ / intranet = ต้องต่อ VPN';
comment on column public.apps.health_url is 'ถ้ากรอก ระบบจะ probe URL นี้เพื่อบอกสถานะออนไลน์บนการ์ด';
comment on column public.apps.sso_url    is 'URL ที่ทำ SSO handshake เช่น https://erp.local/auth-callback.php';

-- -----------------------------------------------------------------------------
-- 3) announcements — ประกาศข่าวสารภายในองค์กร
-- -----------------------------------------------------------------------------
create table if not exists public.announcements (
  id           bigint generated by default as identity primary key,
  title        text not null,
  content      text not null,
  category     text not null default 'General'
                 check (category in ('General', 'HR', 'IT Alert', 'Announcement')),
  is_pinned    boolean not null default false,
  published    boolean not null default true,
  published_at timestamptz not null default now(),
  author_id    text references public.profiles (id) on delete set null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists announcements_feed_idx
  on public.announcements (published, is_pinned desc, published_at desc);

-- -----------------------------------------------------------------------------
-- updated_at trigger
-- -----------------------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_touch      on public.profiles;
drop trigger if exists apps_touch          on public.apps;
drop trigger if exists announcements_touch on public.announcements;

create trigger profiles_touch      before update on public.profiles      for each row execute function public.touch_updated_at();
create trigger apps_touch          before update on public.apps          for each row execute function public.touch_updated_at();
create trigger announcements_touch before update on public.announcements for each row execute function public.touch_updated_at();

-- -----------------------------------------------------------------------------
-- is_admin() — SECURITY DEFINER เพื่อเลี่ยง RLS recursion บนตาราง profiles
-- -----------------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = public.auth0_sub()
      and p.role = 'admin'
      and p.is_active
  );
$$;

-- -----------------------------------------------------------------------------
-- current_role_name() — role ของ user ปัจจุบัน (ใช้เช็ก allowed_roles)
-- -----------------------------------------------------------------------------
create or replace function public.current_role_name()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select p.role from public.profiles p where p.id = public.auth0_sub() and p.is_active),
    'user'
  );
$$;

